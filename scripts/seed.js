async function main() {
  const client = await pool.connect();
  try {
    await client.query("begin");
    for (const source of sources) {
      const capture = captureProfile(source.codigo);
      if (!capture) {
        throw new Error(`Fonte sem mapa de captura: ${source.codigo}`);
      }
      await client.query(
        `insert into fonte (
          codigo, nome, tipo, categoria, url_base, conteudo,
          frequencia_projetos, status_acesso, peculiaridade, ativo,
          participa_scanner, papel_captura, formato_dado,
          auth_acesso, unidade_registro, esfera_noticia, estagio, estagio_desde
        ) values ($1,$2,$3,$4,$5,$6,$7,$8,$9,case when $1 in ('SEC-OBRASGOV','SEC-OBRAS-MG') then false else true end,$10,$11,$12,$13,$14,$15,$16,
          case when $16::text is null then null else now() end)
        on conflict (codigo) do update set
          nome = excluded.nome,
          tipo = excluded.tipo,
          categoria = excluded.categoria,
          url_base = excluded.url_base,
          conteudo = excluded.conteudo,
          frequencia_projetos = excluded.frequencia_projetos,
          status_acesso = excluded.status_acesso,
          peculiaridade = excluded.peculiaridade,
          ativo = case when excluded.codigo in ('SEC-OBRASGOV','SEC-OBRAS-MG') then false else true end,
          participa_scanner = excluded.participa_scanner,
          papel_captura = excluded.papel_captura,
          formato_dado = excluded.formato_dado,
          auth_acesso = excluded.auth_acesso,
          unidade_registro = excluded.unidade_registro,
          esfera_noticia = excluded.esfera_noticia,
          estagio = case
            when fonte.estagio is null then excluded.estagio
            else fonte.estagio
          end,
          estagio_desde = case
            when fonte.estagio is null and excluded.estagio is not null then now()
            else fonte.estagio_desde
          end,
          updated_at = now()`,
        [
          source.codigo,
          source.nome,
          source.tipo,
          source.categoria,
          source.url,
          source.conteudo,
          source.frequencia,
          source.status,
          source.peculiaridade,
          capture.participa_scanner,
          capture.papel_captura,
          capture.formato_dado,
          capture.auth_acesso,
          capture.unidade_registro,
          esferaNoticia(source.codigo),
          capture.participa_scanner ? "fixa" : null,
        ],
      );
    }
    await client.query(
      `update fonte
         set ativo = false,
             peculiaridade = 'Fora de escopo. Contratos e despesas publicas nao sao o recorte do Radar CapEx.',
             updated_at = now()
       where codigo in ('SEC-PDT', 'CAPTURA-DNIT-PDT')`,
    );
    await client.query("commit");
    const primarias = sources.filter((source) => source.tipo === "primaria").length;
    const secundarias = sources.filter((source) => source.tipo === "secundaria").length;
    const noScanner = sources.filter((source) => captureProfile(source.codigo).participa_scanner).length;
    console.log(
      `${sources.length} fontes carregadas (${primarias} primárias, ${secundarias} secundárias, ${noScanner} no scanner).`,
    );
  } catch (error) {
    await client.query("rollback");
    throw error;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((error) => {
  console.error(`Falha no seed: ${error.message}`);
  process.exitCode = 1;
});
